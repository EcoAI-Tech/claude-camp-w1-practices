def get_sign(d: date):
    md = (d.month, d.day)
    result = SIGNS[-1]  # 12/22 之后与 1/20 之前均为摩羯
    for start, *_info in SIGNS:
        if md >= start:
            result = (start, *_info)
    if md < SIGNS[0][0]:
        result = SIGNS[-1]
    start, name, element, traits, color, number = result
    return {
        "name": name,
        "element": element,
        "traits": traits,
        "lucky_color": color,
        "lucky_number": number,
        "element_note": ELEMENT_NOTE[element],
    }
