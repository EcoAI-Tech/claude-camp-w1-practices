def _norm8(n):
    return n % 8 or 8


def cast_by_time(moment: datetime, question_number: int = 0):
    """梅花易数时间起卦（以公历数简化；商业版应换算农历）。

    question_number 可传入求测者报的数（如手机尾号），增强参与感。
    """
    y, m, d, h = moment.year, moment.month, moment.day, moment.hour
    upper = _norm8(y + m + d + question_number)
    lower = _norm8(y + m + d + h + question_number)
    moving = (y + m + d + h + question_number) % 6 or 6
    return build_result(upper, lower, moving, method="梅花易数·时间卦")


def cast_by_coins(rng=None):
    """金钱课：三枚铜钱掷六次，自下而上成卦。"""
    rng = rng or random
    lines = []          # 每爻: 6老阴 7少阳 8少阴 9老阳
    for _ in range(6):
        lines.append(sum(rng.choice([2, 3]) for _ in range(3)))
    yin_yang = [1 if v in (7, 9) else 0 for v in lines]  # 1阳 0阴
    lower = _trigram_from_lines(yin_yang[0:3])
    upper = _trigram_from_lines(yin_yang[3:6])
    moving_lines = [i + 1 for i, v in enumerate(lines) if v in (6, 9)]
    moving = moving_lines[0] if moving_lines else 1
    return build_result(upper, lower, moving, method="金钱课·摇卦")


def _trigram_from_lines(three):
    """三爻(自下而上, 1阳0阴) -> 先天卦数。"""
    table = {(1, 1, 1): 1, (0, 1, 1): 2, (1, 0, 1): 3, (0, 0, 1): 4,
             (1, 1, 0): 5, (0, 1, 0): 6, (1, 0, 0): 7, (0, 0, 0): 8}
    return table[tuple(three)]


def build_result(upper, lower, moving, method):
    name, judgment = HEXAGRAMS[(upper, lower)]
    return {
        "method": method,
        "upper": TRIGRAMS[upper],
        "lower": TRIGRAMS[lower],
        "name": name,
        "judgment": judgment,
        "moving_line": moving,
        "line_hint": LINE_HINT[moving - 1],
    }
